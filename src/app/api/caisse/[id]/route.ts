import { NextRequest, NextResponse } from "next/server";
import { getTenantContext } from "@/lib/auth";
import { resetSessionCreditsOnPaymentDelete } from "@/lib/payments/utils";

export async function PATCH(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { tenantId, supabase } = await getTenantContext();
    const { id } = await params;
    const body = await req.json();

    const { data: existing } = await supabase
      .from("cash_movements")
      .select("*")
      .eq("id", id)
      .eq("tenantId", tenantId)
      .single();

    if (!existing) {
      return NextResponse.json({ error: "Movement not found" }, { status: 404 });
    }

    if (existing.autoGenerated) {
      return NextResponse.json(
        { error: "This transaction is auto-generated. Edit it through the Payments module." },
        { status: 400 }
      );
    }

    const updates: Record<string, unknown> = {};
    if (body.amount !== undefined) updates.amount = Number(body.amount);
    if (body.category !== undefined) updates.category = body.category;
    if (body.description !== undefined) updates.description = body.description;
    if (body.date !== undefined) updates.date = body.date;
    if (body.paymentMethod !== undefined) updates.paymentMethod = body.paymentMethod;

    const { data: updated, error } = await supabase
      .from("cash_movements")
      .update(updates)
      .eq("id", id)
      .select()
      .single();

    if (error) {
      return NextResponse.json({ error: error.message }, { status: 500 });
    }

    return NextResponse.json(updated);
  } catch {
    return NextResponse.json({ error: "Failed to update cash movement" }, { status: 500 });
  }
}

export async function DELETE(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  try {
    const { tenantId, supabase } = await getTenantContext();
    const { id } = await params;

    const { data: existing } = await supabase
      .from("cash_movements")
      .select("*")
      .eq("id", id)
      .eq("tenantId", tenantId)
      .single();

    if (!existing) {
      return NextResponse.json({ error: "Movement not found" }, { status: 404 });
    }

    // If this movement is linked to a payment, also delete the payment and reverse advanceBalance
    if (existing.autoGenerated && existing.referenceId) {
      const { data: payment } = await supabase
        .from("payments")
        .select("id, amountDue, amountPaid, studentId, groupId")
        .eq("id", existing.referenceId)
        .eq("tenantId", tenantId)
        .single();

      if (payment) {
        // Reverse advanceBalance if the payment was overpaid
        if (Number(payment.amountPaid) > Number(payment.amountDue)) {
          const excess = Number(payment.amountPaid) - Number(payment.amountDue);
          const { data: studentData } = await supabase
            .from("students")
            .select("advanceBalance")
            .eq("id", payment.studentId)
            .single();
          const currentAdvance = Number((studentData as any)?.advanceBalance || 0);
          await supabase
            .from("students")
            .update({ advanceBalance: Math.max(0, currentAdvance - excess) })
            .eq("id", payment.studentId);
        }

        // Delete all cash movements linked to this payment
        await supabase.from("cash_movements").delete().eq("referenceId", payment.id).eq("autoGenerated", true);

        // Delete the payment itself
        await supabase.from("payments").delete().eq("id", payment.id);

        await resetSessionCreditsOnPaymentDelete({ supabase, tenantId, studentId: payment.studentId, groupId: payment.groupId ?? null });
      } else {
        // Payment not found, just delete the cash movement
        await supabase.from("cash_movements").delete().eq("id", id);
      }
    } else {
      // Manual movement — just delete it
      await supabase.from("cash_movements").delete().eq("id", id);
    }

    return NextResponse.json({ success: true });
  } catch {
    return NextResponse.json({ error: "Failed to delete cash movement" }, { status: 500 });
  }
}
